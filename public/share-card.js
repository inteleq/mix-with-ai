const clean = (value, limit) => Array.from(String(value ?? "").replace(/mwa_(?:live|test)_[A-Za-z0-9_-]{20,}/g, "[key omitted]").replace(/https?:\/\/\S+/gi, "[link omitted]").replace(/[\u0000-\u001f\u007f]/g, " ").replace(/\s+/g, " ").trim()).slice(0, limit).join("");

export function buildShareDetails({ title, genre, prompt, demo, campaign, includePrompt = false }) {
  const params = new URLSearchParams({ utm_source: "share_card", utm_medium: "social", utm_campaign: /^[a-z0-9-]{1,64}$/.test(campaign ?? "") ? campaign : "music-starter" });
  const details = {
    title: clean(title, 120) || "My next idea",
    genre: clean(genre, 32).replaceAll("_", " ") || "Electronic music",
    source: demo !== false ? "SYNTHESIZED DEMO / NOT MWA-GENERATED" : "CREATED WITH THE MWA API",
    prompt: includePrompt === true ? clean(prompt, 220) : "",
    url: `https://mixwithai.com/?${params}`,
    demo: demo !== false,
  };
  details.caption = `${details.title} · ${details.genre}\n${details.demo ? "A synthesized MWA Starter demo; this audio was not generated by MWA." : "Created with the MWA API."}${details.prompt ? `\nPrompt: ${details.prompt}` : ""}\nBuild your own music app: ${details.url}`;
  return details;
}

function lines(context, text, width, maximum) {
  const characters = Array.from(text);
  const output = []; let line = "";
  for (const character of characters) {
    if (context.measureText(line + character).width > width && line) { output.push(line.trim()); line = character; }
    else line += character;
  }
  if (line) output.push(line.trim());
  if (output.length > maximum) {
    output.length = maximum;
    let final = output.at(-1);
    while (final && context.measureText(`${final}…`).width > width) final = Array.from(final).slice(0, -1).join("");
    output[maximum - 1] = `${final}…`;
  }
  return output;
}

export function drawShareCard(canvas, details) {
  canvas.width = 1200; canvas.height = 630;
  const context = canvas.getContext("2d");
  if (!context) throw new Error("Image export is unavailable in this browser.");
  context.fillStyle = "#f4f2e9"; context.fillRect(0, 0, 1200, 630);
  context.fillStyle = "#1e281e"; context.fillRect(0, 0, 1200, 126);
  context.fillStyle = "#d2fa6a"; context.font = "bold 54px sans-serif"; context.fillText("mwa ↗", 60, 83);
  context.fillStyle = "#f4f2e9"; context.font = "17px monospace"; context.fillText("MAKE MUSIC. BUILD SOMETHING WITH IT.", 464, 76);
  context.fillStyle = "#536249"; context.font = "16px monospace"; context.fillText(details.source, 60, 174);
  context.fillStyle = "#1e281e"; context.font = "bold 62px sans-serif";
  lines(context, details.title, 820, 2).forEach((line, index) => context.fillText(line, 58, 256 + index * 72));
  context.fillStyle = "#536249"; context.font = "24px sans-serif"; context.fillText(`${details.genre} · ${details.demo ? "Starter preview" : "MWA music"}`, 60, 376);
  if (details.prompt) {
    context.font = "18px sans-serif";
    lines(context, `Prompt: ${details.prompt}`, 870, 3).forEach((line, index) => context.fillText(line, 60, 421 + index * 26));
  } else {
    context.font = "22px sans-serif"; context.fillText("Your idea. Your next music app.", 60, 436);
  }
  context.strokeStyle = "#77983c"; context.lineWidth = 7;
  for (let index = 0; index < 8; index++) {
    const height = 48 + Math.sin(index * 1.8) * 30;
    context.beginPath(); context.moveTo(987 + index * 15, 281 - height); context.lineTo(987 + index * 15, 281 + height); context.stroke();
  }
  context.strokeStyle = "#d4d8c8"; context.lineWidth = 1; context.beginPath(); context.moveTo(60, 520); context.lineTo(1140, 520); context.stroke();
  context.fillStyle = "#1e281e"; context.font = "bold 25px sans-serif"; context.fillText("Build with the MWA API ↗", 60, 571);
  context.font = "23px monospace"; context.fillText("mixwithai.com", 880, 571);
  return details;
}
