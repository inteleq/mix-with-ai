import test from "node:test";
import assert from "node:assert/strict";
import { buildShareDetails } from "../public/share-card.js";
import { isGenerationBusy, hasPlayableAudio } from "../public/generation-state.js";

test("sharing excludes prompts by default, identifiers, credentials, and signed URLs", () => {
  const key = `mwa_test_${"x".repeat(40)}`;
  const details = buildShareDetails({ title: "After hours", genre: "tech_house", prompt: `Private prompt ${key}`, demo: false, campaign: "fall-launch", generation_id: "private-id", audioUrl: "https://storage.example/track?token=private", apiKey: key });
  const serialized = JSON.stringify(details);
  for (const privateValue of ["Private prompt", "private-id", "storage.example", key]) assert.ok(!serialized.includes(privateValue));
  assert.equal(details.genre, "tech house");
  const link = new URL(details.url);
  assert.equal(link.origin, "https://mixwithai.com"); assert.equal(link.searchParams.get("utm_campaign"), "fall-launch");
});

test("prompt sharing is explicit, bounded, and removes key-like and URL text", () => {
  const key = `mwa_test_${"x".repeat(40)}`;
  const details = buildShareDetails({ title: "My idea", genre: "house", prompt: `Warm chords ${key} https://storage.example/song?token=private ${"🎵".repeat(400)}`, demo: false, includePrompt: true });
  assert.ok(details.prompt.startsWith("Warm chords [key omitted] [link omitted]"));
  assert.ok(Array.from(details.prompt).length <= 220);
  assert.ok(details.caption.includes(details.prompt)); assert.ok(!details.caption.includes(key)); assert.ok(!details.caption.includes("storage.example"));
});

test("preview cards always disclose their synthesized source and unknown sources stay conservative", () => {
  for (const demo of [true, undefined]) {
    const details = buildShareDetails({ title: "Preview", genre: "house", demo });
    assert.match(details.source, /NOT MWA-GENERATED/); assert.match(details.caption, /not generated by MWA/);
  }
});

test("export recovery keeps polling a failed original audit until audio settles; cancellation remains terminal", () => {
  assert.equal(isGenerationBusy({ status: "failed", audio: { status: "processing" } }), true);
  assert.equal(isGenerationBusy({ status: "failed", audio: { status: "ready", url: "https://files.example/song" } }), false);
  assert.equal(hasPlayableAudio({ status: "failed", audio: { status: "ready", url: "https://files.example/song" } }), true);
  assert.equal(isGenerationBusy({ status: "cancelled", audio: { status: "processing" } }), false);
  assert.equal(isGenerationBusy({ status: "failed", audio: { status: "failed" } }), false);
});
